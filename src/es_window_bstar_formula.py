# es_window_bstar_formula.py
# ------------------------------------------------------------
# 調和バランス法による r, τ, U の数値解（数値実験）から、最小限の当てはめ係数で b*(λ) を再現する【経験式】。
# 解析的に導出した式ではない。
#
# 適用条件（es_core_integrated.py の既定値。この条件でのみ成り立つ）:
#   δ = 0.05, B3 = −0.3, B4 = 0, B5 = 0, χ = 0.8, lam_rate = 0.02
#
# 当てはめに使った λ の 7 点:      λ = 1, 1.5, 2.25, 3, 4, 10, 20
# 独立な検証点（当てはめに未使用）:  λ = 1.25, 2.9, 7, 15   （いずれも当てはめ範囲 1〜20 の内側 = 補間の検証）
#   λ = 1.25, 2.9, 15 は、式の予測値を測定の前に確定して記録したうえで、直接数値シミュレーションで測った。
#   範囲外（λ<1, λ>20）、他の δ・B3・B4・B5・χ・lam_rate では検証していない。
#
# b* の定義:
#   b*(λ) は、正側の持続入力 s の下で、レジーム切替サイクルが消えた直後に現れる
#   「切替のない持続振動（窓）」が存在する最小の b（τ→r の結合の強さ）である。
#   ・持続入力 s: ε の式（dε/dt）に加える一定入力。
#   ・s は各 (b, λ) の s*+（切替サイクルが消える入力）からの相対位置 s*+ + Δ で評価する
#     （Δ = 0.002, 0.004, 0.008, 0.015, 0.03, 0.06 のいずれか。s*+ は二分法で許容 0.0005〜0.001）。
#   ・初期値: 基準の切替サイクル上の位相 0.3 の点。100 周期積分し、最後の 20 周期で判定する。
#   ・「窓」の判定: レジーム切替が 0 回、かつ r の幅が 0.02 を超え、かつ最後の 2 つの 20 周期窓の r の幅の比が 0.9 を超える（減衰しない）。
#   ・b*(λ) は二分法でブラケット (窓なし, 窓あり] を幅 0.0003 程度まで狭めて求める。
#
#   下の式は、閾値でエネルギー収支が閉じる条件（U 経路の供給 = 必要な供給 S_U）を、
#   調和バランスの数値解から当てはめた 1/λ 形の係数で表したものである:
#   b*(λ) = (S_U(λ) − P2(λ)) / P1(λ)
#
# 重要:
# ・S_U(λ), P2(λ), P1(λ) の係数はすべて「調和バランスの数値解からの当てはめ」であり、解析的導出ではない。
# ・係数は独立ではなく、互いに循環的に決まる:  D0 = S0 − P2_0,  D1 = P2_1 − S1
# ・未測定の量（期待値バイアス、調整弾力性など）は導入していない。経済的な意味づけは、数値実験で得られた量に対する解釈にとどまる。
# ・当てはめ 7 点: 数値シミュレーションで探索した b*(λ) のブラケットの中点から最大 0.00020 以内
#   （ブラケット幅は約 0.0003。式がブラケットの外に出る点は 7 点中 5 点で、出る量は最大 0.00007）。
# ・独立な検証 4 点: 中点との差は最大 0.00018（ブラケットの外に出る点は 4 点中 2 点、出る量は最大 0.00005）。
# ・λ→∞ の極限値 0.1214 は、数値実験の外挿値 0.1211〜0.1218（冪の仮定による）の範囲内。
# ・調和バランスは 1 次近似で、閾値の波形には高調波が最大 26% 含まれる。実測の冪は 0.92（1 に固定すると残差 0.0005）。
# ============================================================

# S_U(λ) ≈ S0 − S1/λ : 閾値で赤字（エネルギーの赤字）を埋めるのに必要な U 経路の供給（⟨E⟩ あたりの率）
S0 = 0.13255   # 数値実験の λ→∞ 外挿値（丸めなし）
S1 = 0.00802   # 1/λ 項の係数（丸めなし）

def S_U(lmbd: float) -> float:
    return S0 - S1 / lmbd

# P2(λ) ≈ P2_0 − P2_1/λ : G 経由の供給（τ → G → r の経路）
P2_0 = 0.10762
P2_1 = 0.01753

def P2(lmbd: float) -> float:
    return P2_0 - P2_1 / lmbd

# P1(λ) ≈ P1_0 + P1_1/λ : U → τ → r の直接供給の係数（b を 1 単位増やしたときの供給。供給そのものは b·P1）
# 当てはめの値は P1_0 = 0.20536, P1_1 = 0.02913。ここでは 4 桁に丸めた値を使う。
P1_0 = 0.2054
P1_1 = 0.0291

def P1(lmbd: float) -> float:
    return P1_0 + P1_1 / lmbd

def b_star(lmbd: float) -> float:
    """b*(λ) = (S_U(λ) − P2(λ)) / P1(λ)"""
    return (S_U(lmbd) - P2(lmbd)) / P1(lmbd)


