if __name__ == "__main__":
    def report(title, points):
        print(title)
        print("    λ     ブラケット           中点      式         中点との差   ブラケット")
        worst = 0.0
        for lmbd, (lo, hi) in points.items():
            mid = 0.5 * (lo + hi); b = b_star(lmbd); d = b - mid; worst = max(worst, abs(d))
            where = "内" if lo <= b <= hi else (f"外 ({b - hi:+.5f})" if b > hi else f"外 ({b - lo:+.5f})")
            print(f"  {lmbd:5.2f}  ({lo:.5f},{hi:.5f}]  {mid:.5f}  {b:.5f}   {d:+.5f}     {where}")
        print(f"  中点との差の最大 {worst:.5f}\n")

